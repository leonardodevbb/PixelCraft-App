import { iconPath, type IconName } from './icon-data';

export function Icon({ name, size = 16, className }: { name: IconName; size?: number; className?: string }) {
  return (
    <svg
      className={className}
      width={size}
      height={size}
      viewBox="0 0 16 16"
      shapeRendering="crispEdges"
      aria-hidden="true"
      focusable="false"
    >
      <path d={iconPath(name)} fill="currentColor" />
    </svg>
  );
}
