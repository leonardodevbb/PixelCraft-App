export type IconName = keyof typeof ICONS;

const cache = new Map<string, string>();

/** Converts an icon to a compact SVG path (one rect run per row segment). */
export function iconPath(name: IconName): string {
  const hit = cache.get(name);
  if (hit) return hit;
  const rows = ICONS[name].split('\n').filter((r) => r.length > 0);
  let d = '';
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] === '#') {
        let e = x;
        while (e < row.length && row[e] === '#') e++;
        d += `M${x} ${y}h${e - x}v1h${x - e}z`;
        x = e;
      } else x++;
    }
  });
  cache.set(name, d);
  return d;
}
